"""Generates test/modules/flashcards/fsrs/fsrs_golden_test.dart from the
reference Python implementation (pip install fsrs). Fuzzing is always off so
the output is deterministic.

    python3 tools/gen_fsrs_golden.py
"""
from datetime import datetime, timedelta, timezone
from fsrs import Scheduler, Card, Rating

BASE = datetime(2026, 1, 1, tzinfo=timezone.utc)
M = lambda n: timedelta(minutes=n)
DAY = 1440

# name -> (scheduler kwargs, [(offset_minutes, rating)])
SCENARIOS = {
  "good_path": (dict(), [(0,3),(1,3),(11,3),(11+2*DAY,3),(11+8*DAY,3),(11+25*DAY,3)]),
  "easy_first": (dict(), [(0,4),(4*DAY,3),(15*DAY,4)]),
  "lapse_and_relearn": (dict(), [(0,3),(1,3),(11,3),(4*DAY,3),(4*DAY+10,1),(4*DAY+25,3),(9*DAY,2),(20*DAY,1)]),
  "hard_and_again_in_learning": (dict(), [(0,2),(5,2),(8,1),(9,3),(20,3),(30,3)]),
  "same_day_review_cards": (dict(), [(0,4),(5*DAY,3),(5*DAY+60,3),(5*DAY+120,1),(5*DAY+140,3)]),
  "retention_80_no_steps": (dict(desired_retention=0.8, learning_steps=[], relearning_steps=[]),
                            [(0,3),(DAY,3),(5*DAY,1),(6*DAY,3),(15*DAY,4)]),
  "single_learning_step": (dict(learning_steps=[M(15)], maximum_interval=30),
                           [(0,2),(20,3),(2*DAY,4),(40*DAY,3)]),
}

def rv(x): return repr(float(x))

out = []
out.append("// GENERATED by tools/gen_fsrs_golden.py from py-fsrs (MIT). DO NOT EDIT.")
out.append("import 'dart:math' show Random;")
out.append("")
out.append("import 'package:flutter_test/flutter_test.dart';")
out.append("import 'package:lexiora/modules/flashcards/domain/fsrs/fsrs_scheduler.dart';")
out.append("")
out.append("typedef _Step = ({int at, int rating, int state, int? step, double s, double d, int dueMin});")
out.append("")
out.append("final DateTime _base = DateTime.utc(2026, 1, 1);")
out.append("")
out.append("class _Scenario {")
out.append("  const _Scenario(this.name, this.config, this.steps);")
out.append("  final String name;")
out.append("  final FsrsConfig config;")
out.append("  final List<_Step> steps;")
out.append("}")
out.append("")
out.append("final List<_Scenario> _scenarios = <_Scenario>[")
count = 0
for name,(kw,seq) in SCENARIOS.items():
    sch = Scheduler(enable_fuzzing=False, **kw)
    card = Card(); card.due = BASE
    cfg = ["enableFuzzing: false"]
    if 'desired_retention' in kw: cfg.append(f"desiredRetention: {kw['desired_retention']}")
    if 'learning_steps' in kw:
        cfg.append("learningSteps: <Duration>[" + ", ".join(f"Duration(minutes: {int(x.total_seconds()//60)})" for x in kw['learning_steps']) + "]")
    if 'relearning_steps' in kw:
        cfg.append("relearningSteps: <Duration>[" + ", ".join(f"Duration(minutes: {int(x.total_seconds()//60)})" for x in kw['relearning_steps']) + "]")
    if 'maximum_interval' in kw: cfg.append(f"maximumInterval: {kw['maximum_interval']}")
    out.append(f"  _Scenario('{name}', FsrsConfig({', '.join(cfg)}), <_Step>[")
    for off, r in seq:
        now = BASE + M(off)
        card, _ = sch.review_card(card, Rating(r), now)
        due_min = int((card.due - BASE).total_seconds() // 60)
        st = "null" if card.step is None else str(card.step)
        out.append(f"    (at: {off}, rating: {r}, state: {int(card.state)}, step: {st}, s: {rv(card.stability)}, d: {rv(card.difficulty)}, dueMin: {due_min}),")
        count += 1
    out.append("  ]),")
out.append("];")
out.append("")

# retrievability goldens
sch = Scheduler(enable_fuzzing=False)
c = Card(); c.due = BASE
c, _ = sch.review_card(c, Rating.Good, BASE)
c, _ = sch.review_card(c, Rating.Good, BASE + M(1))
c, _ = sch.review_card(c, Rating.Good, BASE + M(11))
rvs = [(d, sch.get_card_retrievability(c, BASE + M(11) + timedelta(days=d))) for d in (0,1,3,10,60)]
out.append(f"const double _goldenS = {rv(c.stability)};")
out.append("const List<(int, double)> _goldenR = <(int, double)>[")
for d,v in rvs: out.append(f"  ({d}, {rv(v)}),")
out.append("];")
out.append("")
out.append('''void main() {
  const double eps = 1e-9;

  group('FSRS-6 matches the py-fsrs reference', () {
    for (final _Scenario sc in _scenarios) {
      test(sc.name, () {
        final FsrsScheduler sched = FsrsScheduler(sc.config);
        FsrsCard card = FsrsCard.fresh(_base);
        for (final _Step st in sc.steps) {
          final DateTime now = _base.add(Duration(minutes: st.at));
          card = sched.review(card, FsrsRating.fromValue(st.rating), now);
          final String at = '${sc.name} @${st.at}min rating ${st.rating}';
          expect(card.state.value, st.state, reason: '$at state');
          expect(card.step, st.step, reason: '$at step');
          expect(card.stability, closeTo(st.s, eps), reason: '$at stability');
          expect(card.difficulty, closeTo(st.d, eps), reason: '$at difficulty');
          expect(card.due.difference(_base).inMinutes, st.dueMin,
              reason: '$at due');
          expect(card.lastReview, now);
        }
      });
    }
  });

  group('retrievability', () {
    test('matches the reference curve', () {
      final FsrsScheduler sched =
          FsrsScheduler(const FsrsConfig(enableFuzzing: false));
      FsrsCard card = FsrsCard.fresh(_base);
      card = sched.review(card, FsrsRating.good, _base);
      card = sched.review(card, FsrsRating.good, _base.add(const Duration(minutes: 1)));
      card = sched.review(card, FsrsRating.good, _base.add(const Duration(minutes: 11)));
      expect(card.stability, closeTo(_goldenS, eps));
      final DateTime last = _base.add(const Duration(minutes: 11));
      for (final (int days, double r) in _goldenR) {
        expect(sched.retrievability(card, last.add(Duration(days: days))),
            closeTo(r, eps), reason: 'after $days days');
      }
    });

    test('is 0 for a card that was never reviewed', () {
      final FsrsScheduler sched = FsrsScheduler();
      expect(sched.retrievability(FsrsCard.fresh(_base), _base), 0);
    });
  });

  group('behaviour', () {
    test('preview is deterministic and monotonic for a review card', () {
      final FsrsScheduler sched =
          FsrsScheduler(const FsrsConfig(enableFuzzing: false));
      FsrsCard card = FsrsCard.fresh(_base);
      for (final int min in <int>[0, 1, 11]) {
        card = sched.review(card, FsrsRating.good, _base.add(Duration(minutes: min)));
      }
      final DateTime now = _base.add(const Duration(days: 4));
      final Map<FsrsRating, Duration> p = sched.preview(card, now);
      expect(p, sched.preview(card, now));
      expect(p[FsrsRating.again]!, lessThan(p[FsrsRating.hard]!));
      expect(p[FsrsRating.hard]!, lessThanOrEqualTo(p[FsrsRating.good]!));
      expect(p[FsrsRating.good]!, lessThan(p[FsrsRating.easy]!));
    });

    test('fuzz stays inside the documented bounds and skips short intervals', () {
      final FsrsScheduler sched = FsrsScheduler();
      final FsrsCard base = FsrsCard(
        state: FsrsState.review,
        step: null,
        stability: 60,
        difficulty: 5,
        due: _base,
        lastReview: _base,
      );
      final DateTime now = _base.add(const Duration(days: 60));
      final int plain = FsrsScheduler(const FsrsConfig(enableFuzzing: false))
          .review(base, FsrsRating.good, now)
          .due
          .difference(now)
          .inDays;
      // Documented FSRS fuzz half-width for this interval.
      double delta = 1.0;
      for (final (double start, double end, double factor) in <(double, double, double)>[
        (2.5, 7.0, 0.15),
        (7.0, 20.0, 0.1),
        (20.0, double.infinity, 0.05),
      ]) {
        delta += factor * (plain.toDouble().clamp(0.0, end) - start).clamp(0.0, double.infinity);
      }
      final Set<int> seen = <int>{};
      for (int seed = 0; seed < 300; seed++) {
        final FsrsCard c = sched.review(base, FsrsRating.good, now,
            random: _SeededRandom(seed));
        seen.add(c.due.difference(now).inDays);
      }
      expect(seen.length, greaterThan(3), reason: 'fuzz actually varies');
      expect(seen.every((int d) => (d - plain).abs() <= delta.ceil()), isTrue,
          reason: 'within +-$delta of $plain, saw $seen');

      final FsrsScheduler noFuzz =
          FsrsScheduler(const FsrsConfig(enableFuzzing: false));
      final Set<int> fixed = <int>{
        for (int seed = 0; seed < 20; seed++)
          noFuzz.review(base, FsrsRating.good, now, random: _SeededRandom(seed))
              .due.difference(now).inDays,
      };
      expect(fixed.length, 1);
    });

    test('maximumInterval caps the schedule', () {
      final FsrsScheduler sched = FsrsScheduler(
          const FsrsConfig(enableFuzzing: false, maximumInterval: 10));
      final FsrsCard c = sched.review(
        FsrsCard(
          state: FsrsState.review,
          step: null,
          stability: 500,
          difficulty: 3,
          due: _base,
          lastReview: _base,
        ),
        FsrsRating.easy,
        _base.add(const Duration(days: 400)),
      );
      expect(c.due.difference(_base.add(const Duration(days: 400))).inDays, 10);
    });
  });
}

/// Tiny deterministic Random so the fuzz test is reproducible.
class _SeededRandom implements Random {
  _SeededRandom(int seed) : _state = (seed * 2654435761) & 0x7fffffff;
  int _state;

  @override
  double nextDouble() {
    _state = (_state * 1103515245 + 12345) & 0x7fffffff;
    return _state / 0x80000000;
  }

  @override
  bool nextBool() => nextDouble() < 0.5;

  @override
  int nextInt(int max) => (nextDouble() * max).floor();
}
''')
open('test/modules/flashcards/fsrs/fsrs_golden_test.dart','w').write("\n".join(out))
print("steps generated:", count)
